    P.LifeHistories = struct("hex", ["#844836" "#B07156" "#B99364" "#DAC3A9" "#8FA997" "#6BAEB0" "#376988"], "type", "diverging");
    P.theAuk = struct("hex", ["#273A66" "#2073B7" "#7992A6" "#9AB8C9" "#D4D8E2" "#ECBEB6" "#C1847E" "#A13549" "#613A42"], "type", "diverging");
    P.Zoology = struct("hex", ["#7C5A3F" "#906E53" "#AB8C60" "#C8AA77" "#E9C394"], "type", "monochromatic");
    P.FieldNotes = struct("hex", ["#A8B3B2" "#728177" "#3B5D84" "#2073B7" "#59ADDE" "#C08B4C" "#F8D55E"], "type", "qualitative");
